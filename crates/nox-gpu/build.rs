//! Compiles `shaders/*.comp` (GLSL) to SPIR-V in OUT_DIR with glslc or
//! glslangValidator, from PATH or `$VULKAN_SDK/bin`, plus the variants in
//! `VARIANTS`. Shaders can `#include "color_constants.glsl"`, which is
//! generated from nox-color so the GPU uses the same matrices as the CPU.

use nox_color::{OutputTransform, Primaries, Transfer, WORKING_PRIMARIES};
use std::fmt::Write;
use std::path::{Path, PathBuf};
use std::process::Command;

/// Extra builds of a shader with preprocessor defines: (source, output
/// name, defines).
const VARIANTS: &[(&str, &str, &[&str])] = &[
    // Converts into the linear working space (RGBA32F) for compositing.
    ("ycbcr_to_rgb.comp", "ycbcr_to_working", &["WORKING"]),
    // Writes the output as RGBA16F, for AB4H DMA-BUF.
    ("output.comp", "output_f16", &["HALF_FLOAT"]),
];

fn main() {
    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").unwrap());
    println!("cargo:rerun-if-changed=shaders");
    println!("cargo:rerun-if-env-changed=VULKAN_SDK");

    let compiler = find_compiler().unwrap_or_else(|| {
        panic!(
            "no GLSL compiler found: install the Vulkan SDK or glslang (glslc or glslangValidator)"
        )
    });

    std::fs::write(out_dir.join("color_constants.glsl"), color_constants()).unwrap();

    for entry in std::fs::read_dir("shaders").unwrap() {
        let path = entry.unwrap().path();
        if path.extension().is_some_and(|e| e == "comp") {
            let out = out_dir
                .join(path.file_name().unwrap())
                .with_extension("comp.spv");
            compile(&compiler, &path, &out, &out_dir, &[]);
        }
    }
    for (source, name, defines) in VARIANTS {
        let out = out_dir.join(format!("{name}.comp.spv"));
        compile(
            &compiler,
            &Path::new("shaders").join(source),
            &out,
            &out_dir,
            defines,
        );
    }
}

/// GLSL constants for the working space: `Transfer` and `Primaries` values,
/// and the matrices from every `Primaries` to the working space and from
/// the working space to the output.
fn color_constants() -> String {
    // GLSL matrices are column-major.
    let mat3 = |m: [[f32; 3]; 3]| {
        let columns: Vec<String> = (0..3)
            .map(|c| format!("{:?}, {:?}, {:?}", m[0][c], m[1][c], m[2][c]))
            .collect();
        format!("mat3({})", columns.join(",\n    "))
    };
    let mut out = String::from("// Generated by nox-gpu's build.rs from nox-color.\n\n");
    for t in Transfer::ALL {
        let name = format!("{t:?}").to_uppercase();
        writeln!(out, "const int TRANSFER_{name} = {};", t as i32).unwrap();
    }
    for p in Primaries::ALL {
        let name = format!("{p:?}").to_uppercase();
        writeln!(out, "const int PRIMARIES_{name} = {};", p as i32).unwrap();
    }
    // A function rather than a constant array: indexing a `const mat3[]`
    // with a push constant returned wrong matrices (glslang 16, NVIDIA 580).
    out.push_str("\n// Linear RGB in `primaries` (a PRIMARIES_* value) to the working space.\n");
    out.push_str("mat3 to_working(int primaries) {\n");
    for p in Primaries::ALL {
        let name = format!("{p:?}").to_uppercase();
        writeln!(
            out,
            "    if (primaries == PRIMARIES_{name}) {{\n        return {};\n    }}",
            mat3(p.conversion_to(WORKING_PRIMARIES))
        )
        .unwrap();
    }
    out.push_str("    return mat3(1.0);\n}\n");
    writeln!(
        out,
        "\n// The working space to the output primaries.\nconst mat3 WORKING_TO_OUTPUT = {};",
        mat3(WORKING_PRIMARIES.conversion_to(OutputTransform::PRIMARIES))
    )
    .unwrap();
    out
}

enum Compiler {
    Glslc(PathBuf),
    GlslangValidator(PathBuf),
}

fn find_compiler() -> Option<Compiler> {
    let sdk_bin = std::env::var_os("VULKAN_SDK").map(|sdk| PathBuf::from(sdk).join("bin"));
    let candidates = |name: &str| {
        let exe = format!("{name}{}", std::env::consts::EXE_SUFFIX);
        sdk_bin
            .iter()
            .map(move |dir| dir.join(&exe))
            .chain(std::iter::once(PathBuf::from(name)))
    };
    let works = |path: &Path| {
        Command::new(path)
            .arg("--version")
            .output()
            .is_ok_and(|o| o.status.success())
    };
    candidates("glslc")
        .find(|p| works(p))
        .map(Compiler::Glslc)
        .or_else(|| {
            candidates("glslangValidator")
                .find(|p| works(p))
                .map(Compiler::GlslangValidator)
        })
}

fn compile(compiler: &Compiler, input: &Path, output: &Path, include: &Path, defines: &[&str]) {
    let mut cmd = match compiler {
        Compiler::Glslc(exe) => {
            let mut cmd = Command::new(exe);
            cmd.args(["--target-env=vulkan1.3", "-O"]);
            cmd
        }
        Compiler::GlslangValidator(exe) => {
            let mut cmd = Command::new(exe);
            cmd.args(["-V", "--target-env", "vulkan1.3"]);
            cmd
        }
    };
    cmd.arg(format!("-I{}", include.display()));
    for define in defines {
        cmd.arg(format!("-D{define}"));
    }
    cmd.arg("-o").arg(output).arg(input);
    let result = cmd.output().expect("failed to run GLSL compiler");
    if !result.status.success() {
        panic!(
            "compiling {} failed:\n{}{}",
            input.display(),
            String::from_utf8_lossy(&result.stdout),
            String::from_utf8_lossy(&result.stderr)
        );
    }
}
