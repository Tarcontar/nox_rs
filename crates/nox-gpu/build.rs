//! Compiles `shaders/*.comp` (GLSL) to SPIR-V in OUT_DIR (`nox_build`),
//! plus the variants in `VARIANTS`. Shaders can `#include "color_constants.glsl"`, which is
//! generated from nox-color so the GPU uses the same matrices as the CPU.

use nox_color::{OutputEncoding, OutputTransform, Primaries, Transfer, WORKING_PRIMARIES};
use std::fmt::Write;
use std::path::{Path, PathBuf};

#[allow(dead_code)]
mod scope_layout {
    include!("src/scope_layout.rs");
}

/// Extra builds of a shader with preprocessor defines: (source, output
/// name, defines).
const VARIANTS: &[(&str, &str, &[&str])] = &[
    // Converts into the linear working space (RGBA32F) for compositing.
    ("ycbcr_to_rgb.comp", "ycbcr_to_working", &["WORKING"]),
    // Writes the output as RGBA16F, for AB4H DMA-BUF.
    ("output.comp", "output_f16", &["HALF_FLOAT"]),
    // 16-bit outputs, for HDR exports: RGBA16 readback and P010 planes.
    ("output.comp", "output_deep", &["DEEP"]),
    ("output_yuv.comp", "output_yuv_deep", &["DEEP"]),
];

fn main() {
    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").unwrap());
    // Generated headers first: the shaders include them.
    std::fs::write(out_dir.join("color_constants.glsl"), color_constants()).unwrap();
    std::fs::write(out_dir.join("scope_layout.glsl"), scope_constants()).unwrap();
    println!("cargo:rerun-if-changed=src/scope_layout.rs");
    nox_build::compile_shaders(Path::new("shaders"), VARIANTS);
}

/// GLSL constants for the scope images and count buffer.
fn scope_constants() -> String {
    use scope_layout::*;
    let mut out = String::from("// Generated by nox-gpu's build.rs from src/scope_layout.rs.\n\n");
    for (name, value) in [
        ("LEVELS", LEVELS),
        ("WAVEFORM_WIDTH", WAVEFORM_WIDTH),
        ("PARADE_WIDTH", PARADE_WIDTH),
        ("VECTOR_SIZE", VECTOR_SIZE),
        ("HISTOGRAM_BINS", HISTOGRAM_BINS),
        ("HISTOGRAM_HEIGHT", HISTOGRAM_HEIGHT),
        ("WAVEFORM_OFFSET", WAVEFORM_OFFSET),
        ("PARADE_OFFSET", PARADE_OFFSET),
        ("VECTOR_OFFSET", VECTOR_OFFSET),
        ("HISTOGRAM_OFFSET", HISTOGRAM_OFFSET),
        ("HISTOGRAM_MAX_OFFSET", HISTOGRAM_MAX_OFFSET),
    ] {
        writeln!(out, "const int {name} = {value};").unwrap();
    }
    out
}

/// GLSL constants for the working space: `Transfer` and `Primaries` values,
/// and the matrices from every `Primaries` to the working space and from
/// the working space to the output.
fn color_constants() -> String {
    // GLSL matrices are column-major.
    let mat3 = |m: [[f32; 3]; 3]| {
        let columns: Vec<String> = (0..3)
            .map(|c| format!("{:?}, {:?}, {:?}", m[0][c], m[1][c], m[2][c]))
            .collect();
        format!("mat3({})", columns.join(",\n    "))
    };
    let mut out = String::from("// Generated by nox-gpu's build.rs from nox-color.\n\n");
    for t in Transfer::ALL {
        let name = format!("{t:?}").to_uppercase();
        writeln!(out, "const int TRANSFER_{name} = {};", t as i32).unwrap();
    }
    for p in Primaries::ALL {
        let name = format!("{p:?}").to_uppercase();
        writeln!(out, "const int PRIMARIES_{name} = {};", p as i32).unwrap();
    }
    // A function rather than a constant array: indexing a `const mat3[]`
    // with a push constant returned wrong matrices (glslang 16, NVIDIA 580).
    out.push_str("\n// Linear RGB in `primaries` (a PRIMARIES_* value) to the working space.\n");
    out.push_str("mat3 to_working(int primaries) {\n");
    for p in Primaries::ALL {
        let name = format!("{p:?}").to_uppercase();
        writeln!(
            out,
            "    if (primaries == PRIMARIES_{name}) {{\n        return {};\n    }}",
            mat3(p.conversion_to(WORKING_PRIMARIES))
        )
        .unwrap();
    }
    out.push_str("    return mat3(1.0);\n}\n");
    writeln!(
        out,
        "\n// The working space to the output primaries.\nconst mat3 WORKING_TO_OUTPUT = {};",
        mat3(WORKING_PRIMARIES.conversion_to(OutputTransform::PRIMARIES))
    )
    .unwrap();
    writeln!(
        out,
        "\n// The working space to BT.2020, for HDR outputs.\nconst mat3 WORKING_TO_BT2020 = {};",
        mat3(WORKING_PRIMARIES.conversion_to(Primaries::Bt2020))
    )
    .unwrap();
    for e in [OutputEncoding::Sdr, OutputEncoding::Pq, OutputEncoding::Hlg] {
        let name = format!("{e:?}").to_uppercase();
        writeln!(out, "const int ENCODING_{name} = {};", e as i32).unwrap();
    }
    out
}
